// Builds the terminal page the app shows in a WebView: xterm.js and its CSS
// inlined into one HTML string, so terminals work offline and load nothing from
// the network. Runs after every install (postinstall); the output is generated.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(join(root, 'package.json'))
let xtermDir
try {
  xtermDir = dirname(require.resolve('@xterm/xterm/package.json'))
} catch {
  console.log('terminal page: @xterm/xterm is not installed yet; skipped')
  process.exit(0)
}
const script = readFileSync(join(xtermDir, 'lib', 'xterm.js'), 'utf8')
const css = readFileSync(join(xtermDir, 'css', 'xterm.css'), 'utf8')

// The page's own code: draws what the app sends at the computer's terminal size,
// scaled to the phone's width (pinch to zoom). Typing goes through the app's own bar.
const page = `
// The app's WebView on phones; the hosting page when shown in an iframe (the web build).
const post = (m) => {
  const s = JSON.stringify(m);
  if (window.ReactNativeWebView) window.ReactNativeWebView.postMessage(s);
  else if (window.parent !== window) window.parent.postMessage(s, '*');
};
let term = null;
const fit = () => {
  if (!term) return;
  const probe = document.getElementById('probe');
  const ratio = probe.getBoundingClientRect().width / 100 / 10;
  // Fit the computer's width when that stays readable; otherwise keep 9.5px text and pan sideways
  // (agents write mostly from the left edge), with pinch to zoom for anything finer.
  const size = Math.max(9.5, Math.min(15, (window.innerWidth - 8) / (term.cols * ratio)));
  term.options.fontSize = size;
};
const paint = (theme) => { document.documentElement.style.background = theme.background; document.body.style.background = theme.background; };
const handle = (m) => {
  if (m.type === 'init') {
    if (!term) {
      term = new Terminal({ cols: m.cols, rows: m.rows, theme: m.theme, disableStdin: true, scrollback: 5000, fontFamily: 'Menlo, monospace', cursorBlink: false, convertEol: false });
      term.open(document.getElementById('term'));
    } else {
      term.reset();
      term.resize(m.cols, m.rows);
      term.options.theme = m.theme;
    }
    paint(m.theme);
    fit();
    if (m.data) term.write(m.data, () => term.scrollToBottom());
  } else if (m.type === 'write' && term) {
    term.write(m.data);
  } else if (m.type === 'resize' && term) {
    term.resize(m.cols, m.rows);
    fit();
  }
};
const receive = (e) => { try { handle(JSON.parse(e.data)); } catch (err) { post({ type: 'error', message: String(err) }); } };
window.addEventListener('message', receive);
document.addEventListener('message', receive);
window.addEventListener('resize', fit);
post({ type: 'ready' });
`

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=4, user-scalable=yes">
<style>${css}
html,body{margin:0;padding:0;background:transparent;scrollbar-width:none;}::-webkit-scrollbar{display:none;}#term{padding:4px;}
.xterm-viewport{scrollbar-width:none;}
#probe{position:absolute;visibility:hidden;font:10px Menlo,monospace;white-space:pre;}</style></head>
<body><div id="term"></div><span id="probe">${'0'.repeat(100)}</span>
<script>${script}</script><script>${page}</script></body></html>`

const out = join(root, 'src', 'core', 'terminal', 'terminal-html.generated.ts')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, `// Generated by scripts/build-terminal-html.mjs. Do not edit.\nexport const TERMINAL_HTML = ${JSON.stringify(html)}\n`)
console.log(`terminal page: ${Math.round(html.length / 1024)} KB`)
