// Regenerates src/main/services/cli/adapters/icon-data.ts — official CLI marks as data URIs.
// Sources: LobeHub Icons (MIT) for AI brands; official GitHub organization avatars otherwise.
// Usage: node scripts/generate-cli-icons.mjs   (needs network and npm)
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const SILVER = '#DCD6CC'

/** cliId → LobeHub icon file (color variants keep brand colors; mono ones get `color`). */
const LOBE = {
  claude: { file: 'claudecode-color' },
  // The Codex mark is the blue cloud; its white app tile is dropped so it sits on any theme.
  codex: { file: 'codex-color', dropTile: true },
  gemini: { file: 'geminicli-color' },
  opencode: { file: 'opencode', color: SILVER },
  copilot: { file: 'githubcopilot', color: SILVER },
  cursor: { file: 'cursor', color: SILVER },
  qwen: { file: 'qwen-color' },
  amp: { file: 'amp', color: '#F34E3F' },
  goose: { file: 'goose', color: SILVER },
  kimi: { file: 'kimi-color' },
  kiro: { file: 'kiro-color' },
  cline: { file: 'cline', color: SILVER },
  kilocode: { file: 'kilocode', color: '#F8F675' },
  vibe: { file: 'mistral-color' },
  grok: { file: 'grok', color: SILVER },
  openhands: { file: 'openhands-color' },
  junie: { file: 'junie-color' },
  antigravity: { file: 'antigravity-color' },
  hermes: { file: 'hermesagent', color: SILVER },
  devin: { file: 'devin-color' },
  codebuddy: { file: 'codebuddy-color' },
  qoder: { file: 'qoder-color' },
  commandcode: { file: 'commandcode', color: SILVER },
  mimo: { file: 'xiaomimimo', color: '#FF6900' },
  trae: { file: 'trae-color' }
}

/** cliId → GitHub organization that publishes the CLI (its avatar is the official logo). */
const GITHUB = {
  aider: 'Aider-AI',
  crush: 'charmbracelet',
  droid: 'Factory-AI',
  auggie: 'augmentcode',
  continue: 'continuedev',
  plandex: 'plandex-ai',
  letta: 'letta-ai',
  jules: 'google-labs-code',
  rovodev: 'atlassian',
  codebuff: 'CodebuffAI',
  pi: 'earendil-works'
}

const dir = mkdtempSync(join(tmpdir(), 'hiveory-icons-'))
execFileSync('npm', ['pack', '@lobehub/icons-static-svg', '--silent'], { cwd: dir, shell: true })
execFileSync('tar', ['xzf', execFileSync('cmd', ['/c', 'dir', '/b', '*.tgz'], { cwd: dir }).toString().trim()], { cwd: dir })

const uri = (mime, data) => `data:${mime};base64,${Buffer.from(data).toString('base64')}`
const entries = {}
for (const [id, { file, color, dropTile }] of Object.entries(LOBE)) {
  let svg = readFileSync(join(dir, 'package', 'icons', `${file}.svg`), 'utf8')
    .replace(/<title>.*?<\/title>/, '')
    .replace(/ height="1em"| width="1em"| style="[^"]*"/g, '')
  if (color) svg = svg.replace(/currentColor/g, color)
  if (dropTile) svg = svg.replace(/<path [^>]*fill="#fff"><\/path>/, '')
  entries[id] = uri('image/svg+xml', svg)
}
for (const [id, org] of Object.entries(GITHUB)) {
  const res = await fetch(`https://github.com/${org}.png?size=64`)
  if (!res.ok) throw new Error(`avatar ${org}: ${res.status}`)
  entries[id] = uri('image/png', Buffer.from(await res.arrayBuffer()))
}

const body = Object.entries(entries)
  .map(([id, src]) => `  ${JSON.stringify(id)}: ${JSON.stringify(src)},`)
  .join('\n')
writeFileSync(
  'src/main/services/cli/adapters/icon-data.ts',
  `// GENERATED by scripts/generate-cli-icons.mjs — do not edit by hand.
// Official CLI marks: LobeHub Icons (MIT) and official GitHub organization avatars.
// Marks remain their owners' trademarks and are used only to identify each CLI (ADR 0007).
export const CLI_ICONS: Record<string, string> = {
${body}
}
`
)
console.log(`wrote ${Object.keys(entries).length} icons`)
